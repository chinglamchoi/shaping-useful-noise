#!/usr/bin/env python3
from __future__ import annotations

import argparse
import re
from pathlib import Path


PATTERNS = {
    "private key": re.compile(rb"BEGIN (?:RSA |OPENSSH |EC |DSA )?PRIVATE KEY"),
    "API token": re.compile(rb"(?:sk-|hf_)[A-Za-z0-9_-]{20,}"),
    "AWS access key": re.compile(rb"AKIA[0-9A-Z]{16}"),
    "cluster path": re.compile(rb"/data/vision/|/home/[A-Za-z0-9._-]+/"),
    "Slurm account": re.compile(rb"#SBATCH --(?:account|partition|qos)="),
    "email address": re.compile(rb"[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}", re.I),
    "AI attribution": re.compile(rb"(?:ChatGPT|GitHub Copilot|generated by (?:AI|Claude)|as an AI)", re.I),
}


def main() -> None:
    parser = argparse.ArgumentParser(description="Scan a release tree for credentials and private infrastructure details.")
    parser.add_argument("root", type=Path, nargs="?", default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()

    findings = []
    for path in sorted(item for item in args.root.rglob("*") if item.is_file() and ".git" not in item.parts):
        if path.resolve() == Path(__file__).resolve():
            continue
        data = path.read_bytes()
        for label, pattern in PATTERNS.items():
            if pattern.search(data):
                findings.append((path.relative_to(args.root), label))
    if findings:
        for path, label in findings:
            print(f"{label}: {path}")
        raise SystemExit(1)
    print(f"release audit passed: {args.root}")


if __name__ == "__main__":
    main()
